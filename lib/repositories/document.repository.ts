import {
  type DocVisibility,
  type DocShareRole,
  DocMentionSource,
  type Prisma,
} from '@prisma/client'
import { prisma } from '@/lib/db/prisma'
import { buildDocumentSlug } from '@/lib/utils/document-slug'

// ── Types ───────────────────────────────────────────────────────────────────

export interface CreateDocumentData {
  title: string
  emoji?: string | null
  parentId?: string | null
  projectId?: string | null
  workspaceId: string
  createdById: string
  visibility: DocVisibility
  sortOrder: number
  content?: string | null
  // Byte-identical markdown source when the body arrived as markdown (LUM-408).
  sourceMarkdown?: string | null
  // Google Docs import source (LUM-127). Null for native docs.
  googleDocId?: string | null
  googleDocImporterId?: string | null
  googleDocSyncedAt?: Date | null
}

export interface DocumentUpdateData {
  title?: string
  content?: string | null
  // Markdown source double-write / invalidation (LUM-408): set to the raw
  // markdown when the update carried contentMarkdown, explicitly null when
  // content was replaced through the HTML-direct path.
  sourceMarkdown?: string | null
  emoji?: string | null
  visibility?: DocVisibility | string
  projectId?: string | null
  sortOrder?: number
  publicToken?: string | null
  tags?: string[]
  // Regenerated by the service when the title changes; `number` is immutable
  // post-create but listed here for completeness in the type contract.
  slug?: string
  // Google Docs one-way sync bookkeeping (LUM-127).
  googleDocSyncedAt?: Date | null
  googleDocSyncError?: string | null
}

export interface DocumentFilters {
  visibility?: string
  projectId?: string
  parentId?: string | null
  search?: string
  rootOnly?: boolean
}

export interface DocumentTreeFilter {
  workspaceId: string
  parentId?: string | null
  createdById?: string
  visibility?: DocVisibility
  OR?: Array<Record<string, unknown>>
}

// ── Shared includes ─────────────────────────────────────────────────────────

const DOCUMENT_LIST_INCLUDE = {
  project: { select: { id: true, name: true } },
  createdBy: { select: { id: true, clerkId: true } },
  shares: {
    include: {
      member: { select: { id: true, clerkId: true } },
    },
  },
  editors: {
    select: {
      member: { select: { id: true, clerkId: true } },
      lastEditedAt: true,
    },
    orderBy: { lastEditedAt: 'desc' as const },
    take: 5,
  },
  _count: { select: { children: { where: { deletedAt: null } } } },
} as const

const DOCUMENT_DETAIL_INCLUDE = {
  project: { select: { id: true, name: true } },
  createdBy: { select: { id: true, clerkId: true } },
  // LUM-918: relation reads bypass the soft-delete extension — filter here.
  children: {
    where: { deletedAt: null },
    orderBy: { sortOrder: 'asc' as const },
    select: {
      id: true,
      slug: true,
      title: true,
      emoji: true,
      parentId: true,
      sortOrder: true,
      updatedAt: true,
      _count: { select: { children: { where: { deletedAt: null } } } },
    },
  },
  shares: {
    include: {
      member: { select: { id: true, clerkId: true } },
    },
  },
  mentions: {
    where: { task: { deletedAt: null } },
    include: {
      task: {
        select: {
          id: true,
          number: true,
          team: { select: { identifier: true } },
        },
      },
    },
  },
  _count: { select: { children: { where: { deletedAt: null } } } },
} as const

// ── Repository ──────────────────────────────────────────────────────────────

export const documentRepository = {
  /** Find documents in workspace with permission filtering. */
  async findByWorkspace(
    workspaceId: string,
    memberId: string,
    filters?: DocumentFilters
  ) {
    const where: {
      workspaceId: string
      createdById?: string
      visibility?: DocVisibility
      projectId?: string
      parentId?: string | null
      title?: { contains: string; mode: 'insensitive' }
      OR?: Array<Record<string, unknown>>
    } = {
      workspaceId,
      OR: [
        { createdById: memberId },
        { visibility: 'WORKSPACE' as const },
        { shares: { some: { memberId } } },
      ],
    }

    if (filters?.visibility === 'PRIVATE') {
      where.createdById = memberId
      where.visibility = 'PRIVATE'
      delete where.OR
    } else if (filters?.visibility === 'SHARED') {
      where.visibility = 'SHARED'
    } else if (filters?.visibility === 'WORKSPACE') {
      where.visibility = 'WORKSPACE'
    }

    if (filters?.projectId) where.projectId = filters.projectId
    if (filters?.parentId) where.parentId = filters.parentId
    if (filters?.parentId === null || filters?.rootOnly) {
      where.parentId = null
    }
    if (filters?.search) {
      where.title = { contains: filters.search, mode: 'insensitive' }
    }

    return prisma.document.findMany({
      where,
      include: DOCUMENT_LIST_INCLUDE,
      orderBy: [{ updatedAt: 'desc' }],
    })
  },

  /**
   * Find document with permission check. Accepts either the cuid `id` or the
   * workspace-unique `slug` as the lookup key — cuid and slug never share a
   * shape (cuids have no `-`, slugs always end in `-<number>`), so a single
   * OR query resolves either form without ambiguity.
   */
  async findWithPermission(
    idOrSlug: string,
    memberId: string,
    workspaceId: string
  ) {
    return prisma.document.findFirst({
      where: {
        workspaceId,
        AND: [
          { OR: [{ id: idOrSlug }, { slug: idOrSlug }] },
          {
            OR: [
              { createdById: memberId },
              { visibility: 'WORKSPACE' },
              { shares: { some: { memberId } } },
            ],
          },
        ],
      },
      include: DOCUMENT_DETAIL_INCLUDE,
    })
  },

  /** Find a publicly shared document by its public token. */
  async findByPublicToken(token: string) {
    return prisma.document.findUnique({
      where: { publicToken: token },
      select: {
        title: true,
        emoji: true,
        content: true,
      },
    })
  },

  /**
   * Find document for basic existence check. Accepts cuid or slug; same
   * resolution rules as `findWithPermission`.
   */
  async findById(idOrSlug: string, workspaceId: string) {
    return prisma.document.findFirst({
      where: {
        workspaceId,
        OR: [{ id: idOrSlug }, { slug: idOrSlug }],
      },
    })
  },

  /** Get max sortOrder among sibling documents. */
  async getMaxSortOrder(workspaceId: string, parentId: string | null) {
    const maxSibling = await prisma.document.findFirst({
      where: { parentId, workspaceId },
      orderBy: { sortOrder: 'desc' },
      select: { sortOrder: true },
    })
    return maxSibling?.sortOrder ?? 0
  },

  /**
   * Create a new document. Atomically allocates the next per-workspace
   * `number` via `workspace.documentSeq` (mirrors how Team.taskSeq feeds
   * Task.number) and stores the derived `slug` together with the insert.
   */
  async create(data: CreateDocumentData) {
    return prisma.$transaction(async tx => {
      const { documentSeq } = await tx.workspace.update({
        where: { id: data.workspaceId },
        data: { documentSeq: { increment: 1 } },
        select: { documentSeq: true },
      })

      const slug = buildDocumentSlug(data.title, documentSeq)

      return tx.document.create({
        data: {
          title: data.title,
          emoji: data.emoji ?? null,
          parentId: data.parentId ?? null,
          projectId: data.projectId ?? null,
          workspaceId: data.workspaceId,
          createdById: data.createdById,
          visibility: data.visibility,
          sortOrder: data.sortOrder,
          number: documentSeq,
          slug,
          googleDocId: data.googleDocId ?? null,
          googleDocImporterId: data.googleDocImporterId ?? null,
          googleDocSyncedAt: data.googleDocSyncedAt ?? null,
          ...(data.content !== undefined ? { content: data.content } : {}),
          ...(data.sourceMarkdown !== undefined
            ? { sourceMarkdown: data.sourceMarkdown }
            : {}),
        },
        include: {
          project: { select: { id: true, name: true } },
          createdBy: { select: { id: true, clerkId: true } },
          _count: { select: { children: { where: { deletedAt: null } } } },
        },
      })
    })
  },

  /** Find a document by the Google Drive fileId it mirrors (LUM-127). */
  findByGoogleDocId(workspaceId: string, googleDocId: string) {
    return prisma.document.findFirst({
      where: { workspaceId, googleDocId },
    })
  },

  /** Read just the Google import source metadata for a doc (LUM-127). */
  findSourceMeta(id: string, workspaceId: string) {
    return prisma.document.findFirst({
      where: { id, workspaceId },
      select: {
        id: true,
        googleDocId: true,
        googleDocImporterId: true,
        googleDocSyncedAt: true,
      },
    })
  },

  /** Update document fields. */
  async update(id: string, data: DocumentUpdateData) {
    return prisma.document.update({
      where: { id },
      data: data as Parameters<typeof prisma.document.update>[0]['data'],
    })
  },

  /**
   * Update only the rendered body content. Unlike `update`, this accepts an
   * outer transaction so a content write can be grouped atomically with mention
   * inserts by the caller.
   */
  async updateContent(
    id: string,
    content: string,
    tx?: Prisma.TransactionClient
  ) {
    const client = tx ?? prisma
    return client.document.update({
      where: { id },
      data: { content },
    })
  },

  /**
   * Batch-insert doc↔task mentions, skipping duplicates. Accepts an outer
   * transaction so the caller can group it with a content update.
   */
  async createMentions(
    rows: { documentId: string; taskId: string; source: DocMentionSource }[],
    tx?: Prisma.TransactionClient
  ) {
    if (rows.length === 0) return { count: 0 }
    const client = tx ?? prisma
    return client.documentMention.createMany({
      data: rows,
      skipDuplicates: true,
    })
  },

  /** Cache the LLM-generated body summary (LUM-122). */
  async updateSummary(id: string, summary: string) {
    return prisma.document.update({
      where: { id },
      data: { summary, summaryGeneratedAt: new Date() },
    })
  },

  /**
   * Add or upgrade a doc↔task mention as EXPLICIT.
   * If an EXPLICIT row exists, no-op. If a CONTENT row exists, upgrade to EXPLICIT.
   */
  async addExplicitMention(documentId: string, taskId: string) {
    return prisma.documentMention.upsert({
      where: { documentId_taskId: { documentId, taskId } },
      create: { documentId, taskId, source: DocMentionSource.EXPLICIT },
      update: { source: DocMentionSource.EXPLICIT },
    })
  },

  /**
   * Delete an explicit mention. Returns the number of rows deleted (0 or 1).
   * Refuses to delete CONTENT-sourced rows (where clause filters by source).
   */
  async removeExplicitMention(
    documentId: string,
    taskId: string
  ): Promise<number> {
    const result = await prisma.documentMention.deleteMany({
      where: { documentId, taskId, source: DocMentionSource.EXPLICIT },
    })
    return result.count
  },

  /** Returns the source of an existing mention row, or null if none exists. */
  async findMention(documentId: string, taskId: string) {
    return prisma.documentMention.findUnique({
      where: { documentId_taskId: { documentId, taskId } },
      select: { source: true },
    })
  },

  /**
   * Update document with optional child reordering and mention sync, all in a
   * single transaction.
   *
   * Optimistic concurrency (LUM-409): any update that touches `content` also
   * increments `contentRevision`. When `expectedContentRevision` is provided
   * the row update is CONDITIONAL (`where: { id, contentRevision }`) — a
   * concurrent writer that bumped the revision first makes the count 0 and
   * the whole transaction rolls back with a `REVISION_CONFLICT`-coded error,
   * so a stale write can never silently last-write-win.
   */
  async updateWithChildrenAndMentions(
    id: string,
    updateData: DocumentUpdateData,
    childOrder: string[] | undefined,
    mentionTaskIds: string[] | undefined,
    options?: { expectedContentRevision?: number }
  ) {
    return prisma.$transaction(async tx => {
      const data = {
        ...updateData,
        ...(updateData.content !== undefined
          ? { contentRevision: { increment: 1 } }
          : {}),
      } as Parameters<typeof tx.document.update>[0]['data']

      let updatedDoc
      if (Object.keys(updateData).length === 0) {
        updatedDoc = await tx.document.findUniqueOrThrow({ where: { id } })
      } else if (options?.expectedContentRevision !== undefined) {
        const res = await tx.document.updateMany({
          where: { id, contentRevision: options.expectedContentRevision },
          data,
        })
        if (res.count === 0) {
          throw Object.assign(
            new Error(
              `contentRevision mismatch for ${id} (expected ${options.expectedContentRevision})`
            ),
            { code: 'REVISION_CONFLICT' }
          )
        }
        updatedDoc = await tx.document.findUniqueOrThrow({ where: { id } })
      } else {
        updatedDoc = await tx.document.update({ where: { id }, data })
      }

      // Reorder children if childOrder is provided
      if (childOrder) {
        for (let i = 0; i < childOrder.length; i++) {
          await tx.document.update({
            where: { id: childOrder[i]! },
            data: { sortOrder: i },
          })
        }
      }

      // Sync mentions if mentionTaskIds is provided.
      // Only replaces source=CONTENT rows; EXPLICIT rows are preserved across content edits.
      if (mentionTaskIds !== undefined) {
        const existingContent = await tx.documentMention.findMany({
          where: { documentId: id, source: DocMentionSource.CONTENT },
          select: { taskId: true },
        })
        const existingContentIds = new Set(existingContent.map(m => m.taskId))
        const newIds = new Set(mentionTaskIds)

        const toDelete = [...existingContentIds].filter(mid => !newIds.has(mid))
        if (toDelete.length > 0) {
          // belt-and-suspenders: toDelete is already CONTENT-only from the findMany above
          await tx.documentMention.deleteMany({
            where: {
              documentId: id,
              taskId: { in: toDelete },
              source: DocMentionSource.CONTENT,
            },
          })
        }

        // Determine which mentionTaskIds need a new row. Skip any that
        // already exist (as either CONTENT or EXPLICIT) — for CONTENT
        // they're a no-op match; for EXPLICIT they were explicitly bound
        // and the content node is redundant with no semantic change.
        const allExisting = await tx.documentMention.findMany({
          where: { documentId: id },
          select: { taskId: true },
        })
        const everExisting = new Set(allExisting.map(m => m.taskId))
        const toCreate = [...newIds].filter(mid => !everExisting.has(mid))
        if (toCreate.length > 0) {
          await tx.documentMention.createMany({
            data: toCreate.map(taskId => ({
              documentId: id,
              taskId,
              source: DocMentionSource.CONTENT,
            })),
          })
        }
      }

      return updatedDoc
    })
  },

  /** Find a single document node with its children (used by ancestor chain walker). */
  async findNodeWithChildren(id: string) {
    return prisma.document.findUnique({
      where: { id },
      select: {
        id: true,
        slug: true,
        title: true,
        emoji: true,
        parentId: true,
        children: {
          where: { deletedAt: null },
          orderBy: { sortOrder: 'asc' },
          select: {
            id: true,
            slug: true,
            title: true,
            emoji: true,
            _count: { select: { children: { where: { deletedAt: null } } } },
          },
        },
      },
    })
  },

  /** Find a document node by ID (for tree traversal, parentId only). */
  async findParentId(id: string) {
    return prisma.document.findUnique({
      where: { id },
      select: { id: true, parentId: true },
    })
  },

  /** Find tree nodes (documents matching a filter, for sidebar tree). */
  async findTreeNodes(filter: DocumentTreeFilter) {
    return prisma.document.findMany({
      where: filter,
      orderBy: { sortOrder: 'asc' },
      select: {
        id: true,
        slug: true,
        title: true,
        emoji: true,
        parentId: true,
        sortOrder: true,
        _count: { select: { children: { where: { deletedAt: null } } } },
      },
    })
  },

  /** Find a document the member can manage (owner or MANAGER share). */
  async findManageable(
    idOrSlug: string,
    memberId: string,
    workspaceId: string
  ) {
    return prisma.document.findFirst({
      where: {
        workspaceId,
        AND: [
          { OR: [{ id: idOrSlug }, { slug: idOrSlug }] },
          {
            OR: [
              { createdById: memberId },
              { shares: { some: { memberId, role: 'MANAGER' } } },
            ],
          },
        ],
      },
    })
  },

  /** Find a document the member can edit (owner, WORKSPACE visibility, or EDITOR/MANAGER share). */
  async findEditable(idOrSlug: string, memberId: string, workspaceId: string) {
    return prisma.document.findFirst({
      where: {
        workspaceId,
        AND: [
          { OR: [{ id: idOrSlug }, { slug: idOrSlug }] },
          {
            OR: [
              { createdById: memberId },
              { visibility: 'WORKSPACE' },
              {
                shares: {
                  some: {
                    memberId,
                    role: { in: ['EDITOR', 'MANAGER'] },
                  },
                },
              },
            ],
          },
        ],
      },
      include: { workspace: { select: { slug: true } } },
    })
  },

  /** Find all shares for a document with member info. */
  async findSharesByDocument(documentId: string) {
    return prisma.documentShare.findMany({
      where: { documentId },
      include: {
        member: {
          select: { id: true, clerkId: true },
        },
      },
      orderBy: { createdAt: 'asc' },
    })
  },

  /** Create or update a document share in a transaction (auto-sets visibility to SHARED if PRIVATE). */
  async upsertShareTransaction(
    documentId: string,
    memberId: string,
    role: DocShareRole,
    currentVisibility: string
  ) {
    return prisma.$transaction(async tx => {
      if (currentVisibility === 'PRIVATE') {
        await tx.document.update({
          where: { id: documentId },
          data: { visibility: 'SHARED' },
        })
      }

      return tx.documentShare.upsert({
        where: {
          documentId_memberId: { documentId, memberId },
        },
        create: { documentId, memberId, role },
        update: { role },
        include: {
          member: {
            select: { id: true, clerkId: true },
          },
        },
      })
    })
  },

  /** Update a document share's role. */
  async updateShare(shareId: string, role: DocShareRole) {
    return prisma.documentShare.update({
      where: { id: shareId },
      data: { role },
    })
  },

  /** Delete a document share. */
  async deleteShare(shareId: string) {
    return prisma.documentShare.delete({ where: { id: shareId } })
  },

  /** Move a document (update parentId and sortOrder). */
  async move(id: string, parentId: string | null, sortOrder: number) {
    return prisma.document.update({
      where: { id },
      data: { parentId, sortOrder },
    })
  },

  /** Upsert document editor tracking. */
  async upsertEditor(documentId: string, memberId: string) {
    return prisma.documentEditor.upsert({
      where: {
        documentId_memberId: { documentId, memberId },
      },
      update: { lastEditedAt: new Date() },
      create: { documentId, memberId },
    })
  },
}
