/**
 * LUM-413: failure-attribution re-run over the LUM-392 extraction.
 *
 * Run extract first (refreshes out/invocations.jsonl from prod, read-only):
 *   npx tsx scripts/analysis/lum392-cli-friction/extract.ts
 * Then:
 *   npx tsx scripts/analysis/lum392-cli-friction/run-attribution.ts
 *
 * Adds, on top of every extracted invocation:
 *   - AST verdict (validate.ts against the committed grammar.json)
 *   - five-class result label (attribute.ts)
 *   - Winston root-cause suggestion (rootcause.ts; review worksheet)
 * and computes the three side checks: masked-failure audit, SKILL.md trigger
 * recall (one read-only prod query for Skill-tool loads), self-conditioning
 * clustering.
 *
 * Outputs:
 *   out/attribution.jsonl   (per-invocation labels; gitignored like the rest)
 *   out/attribution.json    (aggregates)
 *   REPORT-lum413.md        (committed report, regenerated by this script)
 */
import { config } from 'dotenv'
import { readdirSync, readFileSync, writeFileSync } from 'fs'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'
import {
  classifySession,
  clusteringStats,
  type AttributionInput,
  type AttributionOutput,
  type ResultClass,
} from './attribute'
import type { CliGrammar } from './grammar'
import { suggestRootCause, type RootCauseSuggestion } from './rootcause'
import { validateSegment, type AstVerdict } from './validate'

config({ path: process.env.DOTENV_CONFIG_PATH ?? '.env.production' })

const HERE = dirname(fileURLToPath(import.meta.url))

interface InvocationRecord extends Omit<
  AttributionInput,
  'astVerdict' | 'astOffending'
> {
  sessionId: string | null
  taskId: string | null
  siblings: number
  durationMs: number | null
}

interface LabeledRecord extends InvocationRecord {
  ast: AstVerdict
  resultClass: ResultClass
  classReason: string
  maskedFailure: boolean
  rootCause: RootCauseSuggestion | null
}

/**
 * Skill docs corpus for the R2-vs-R5 disambiguation (is the hallucinated
 * token advertised by the docs?). The SKILL.md anti-pattern section lists
 * commands/flags that do NOT exist — those mentions are warnings, not
 * advertisements, so the section is stripped before matching.
 */
function loadSkillDocsCorpus(): string {
  const root = join(HERE, '../../../.claude/skills/lumo')
  const parts: string[] = []
  const readDir = (dir: string) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const p = join(dir, entry.name)
      if (entry.isDirectory()) readDir(p)
      else if (entry.name.endsWith('.md')) parts.push(readFileSync(p, 'utf8'))
    }
  }
  readDir(root)
  return parts
    .join('\n')
    .replace(/^## Commands & flags that do NOT exist[\s\S]*?(?=^## )/m, '')
}

function offendingInDocs(corpus: string, ast: AstVerdict): boolean {
  if (!ast.offending) return false
  if (ast.kind === 'unknown-flag') return corpus.includes(ast.offending)
  if (ast.kind === 'unknown-command') {
    const attempted = [ast.commandPath, ast.offending].filter(Boolean).join(' ')
    return (
      corpus.includes(`lumo ${attempted}`) ||
      corpus.includes(`\`${attempted}\``)
    )
  }
  return false
}

const pct = (n: number, d: number) =>
  d === 0 ? '0' : ((n / d) * 100).toFixed(1)

async function main() {
  const grammar = JSON.parse(
    readFileSync(join(HERE, 'grammar.json'), 'utf8')
  ) as CliGrammar
  const corpus = loadSkillDocsCorpus()
  const records: InvocationRecord[] = readFileSync(
    join(HERE, 'out/invocations.jsonl'),
    'utf8'
  )
    .trim()
    .split('\n')
    .map(l => JSON.parse(l) as InvocationRecord)

  // ---- per-record AST verdicts, then per-session five-class labels ----
  // extract.ts caps raw length; a truncated segment can cut a quoted body
  // open and leak fake flag tokens — those records are not judged.
  const TRUNCATED_RAW = 2000
  const asts = records.map(r =>
    r.raw.length >= TRUNCATED_RAW
      ? ({
          kind: 'valid',
          commandPath: '',
          offending: null,
          detail: 'skipped: truncated raw',
        } as AstVerdict)
      : validateSegment(r.raw, grammar)
  )
  const truncatedSkipped = records.filter(
    r => r.raw.length >= TRUNCATED_RAW
  ).length
  const bySession = new Map<string, number[]>()
  records.forEach((r, i) => {
    const key = r.sessionId ?? `__solo__${i}`
    const list = bySession.get(key) ?? []
    list.push(i)
    bySession.set(key, list)
  })

  const labels: (AttributionOutput | null)[] = records.map(() => null)
  for (const indices of bySession.values()) {
    indices.sort(
      (a, b) =>
        records[a]!.createdAt.localeCompare(records[b]!.createdAt) || a - b
    )
    const inputs: AttributionInput[] = indices.map(i => ({
      ...records[i]!,
      astVerdict: asts[i]!.kind,
      astOffending: asts[i]!.offending,
    }))
    const outputs = classifySession(inputs)
    indices.forEach((origIdx, k) => {
      labels[origIdx] = outputs[k]!
    })
  }

  const labeled: LabeledRecord[] = records.map((r, i) => {
    const ast = asts[i]!
    const label = labels[i]!
    return {
      ...r,
      ast,
      resultClass: label.resultClass,
      classReason: label.reason,
      maskedFailure: label.maskedFailure,
      rootCause: suggestRootCause({
        resultClass: label.resultClass,
        reason: label.reason,
        errorKind: r.errorKind,
        evidence: r.evidence,
        maskedFailure: label.maskedFailure,
        astOffending: ast.offending,
        offendingInSkillDocs: offendingInDocs(corpus, ast),
      }),
    }
  })

  // ---- aggregates ----
  const total = labeled.length
  const byClass = new Map<ResultClass, LabeledRecord[]>()
  for (const r of labeled) {
    byClass.set(r.resultClass, [...(byClass.get(r.resultClass) ?? []), r])
  }
  const classOrder: ResultClass[] = [
    'valid-result',
    'redundant-valid',
    'usage-error',
    'selection-error',
    'invalid-result',
  ]

  const byCause = new Map<string, LabeledRecord[]>()
  for (const r of labeled) {
    if (!r.rootCause) continue
    const key = r.rootCause.cause
    byCause.set(key, [...(byCause.get(key) ?? []), r])
  }

  const astInvalid = labeled.filter(r => r.ast.kind !== 'valid')
  const flagHallucinations = labeled.filter(r => r.ast.kind === 'unknown-flag')
  const enumViolations = labeled.filter(r => r.ast.kind === 'illegal-enum')
  const unknownCommands = labeled.filter(r => r.ast.kind === 'unknown-command')
  // Structurally illegal per the help text, yet succeeded at run time: the
  // CLI accepts what its own docs forbid (or the agent suppressed stderr).
  const docDrift = labeled.filter(r => r.ast.kind !== 'valid' && !r.errored)
  const docDriftGroups = new Map<string, LabeledRecord[]>()
  for (const r of docDrift) {
    const key = `${r.ast.kind} · ${r.ast.commandPath || '(root)'} · ${r.ast.offending ?? '(missing subcommand)'}`
    docDriftGroups.set(key, [...(docDriftGroups.get(key) ?? []), r])
  }
  const statusWalks = labeled.filter(
    r => r.classReason === 'redundant:status-walk-superseded'
  )
  const identicalRepeats = labeled.filter(
    r => r.classReason === 'redundant:identical-repeat'
  )
  const unhelpfulErrors = labeled.filter(r =>
    r.rootCause?.rationale.includes('R5 candidate')
  )

  // ---- side check 1: masked failures ----
  const exitZero = labeled.filter(r => !r.errored)
  const masked = labeled.filter(r => r.maskedFailure)
  const headlineErrors = labeled.filter(r => r.errored)

  // ---- side check 2: SKILL.md trigger recall (one read-only prod query) ----
  const { prisma } = await import('@/lib/db/prisma')
  const { openHookPayloads } = await import('@/lib/hook-event/payload-cipher')
  // LUM-863: payloads may be encrypted — match the skill name after decryption.
  const skillLoadRows = (
    await openHookPayloads(
      await prisma.hookEvent.findMany({
        where: { type: 'PRE_TOOL_USE', toolName: 'Skill' },
        select: { sessionId: true, payload: true, payloadEncrypted: true },
      })
    )
  ).filter(
    r =>
      (r.payload as { tool_input?: { skill?: unknown } } | null)?.tool_input
        ?.skill === 'lumo'
  )
  await prisma.$disconnect()
  const skillSessions = new Set(
    skillLoadRows.map(r => r.sessionId).filter(Boolean)
  )
  const lumoSessions = new Set(
    records.map(r => r.sessionId).filter((s): s is string => Boolean(s))
  )
  const withSkill = [...lumoSessions].filter(s => skillSessions.has(s))
  // Weekly recall series (the description-trim watch item is a time trend).
  const weekOf = (iso: string) => {
    const d = new Date(iso)
    const day = (d.getUTCDay() + 6) % 7
    d.setUTCDate(d.getUTCDate() - day)
    return d.toISOString().slice(0, 10)
  }
  const sessionWeek = new Map<string, string>()
  for (const r of records) {
    if (!r.sessionId) continue
    const w = weekOf(r.createdAt)
    const prev = sessionWeek.get(r.sessionId)
    if (!prev || w < prev) sessionWeek.set(r.sessionId, w)
  }
  const weeklyRecall = new Map<string, { total: number; loaded: number }>()
  for (const [sid, week] of sessionWeek) {
    const agg = weeklyRecall.get(week) ?? { total: 0, loaded: 0 }
    agg.total++
    if (skillSessions.has(sid)) agg.loaded++
    weeklyRecall.set(week, agg)
  }

  // ---- side check 3: self-conditioning ----
  const sessionClasses: ResultClass[][] = []
  for (const [key, indices] of bySession) {
    if (key.startsWith('__solo__')) continue
    sessionClasses.push(indices.map(i => labeled[i]!.resultClass))
  }
  const clustering = clusteringStats(sessionClasses)

  // ---- outputs ----
  const aggregates = {
    generatedFor: 'LUM-413',
    grammarCliVersion: grammar.cliVersion,
    coverage: {
      invocations: total,
      sessions: lumoSessions.size,
      from: records.reduce(
        (m, r) => (r.createdAt < m ? r.createdAt : m),
        records[0]!.createdAt
      ),
      to: records.reduce(
        (m, r) => (r.createdAt > m ? r.createdAt : m),
        records[0]!.createdAt
      ),
    },
    fiveClassDistribution: Object.fromEntries(
      classOrder.map(c => [
        c,
        {
          count: byClass.get(c)?.length ?? 0,
          pct: pct(byClass.get(c)?.length ?? 0, total),
        },
      ])
    ),
    astVerdicts: {
      invalidConstructions: astInvalid.length,
      unknownFlag: flagHallucinations.length,
      illegalEnum: enumViolations.length,
      unknownCommand: unknownCommands.length,
      truncatedSkipped,
      acceptedAtRuntime: docDrift.length,
    },
    docDrift: Object.fromEntries(
      [...docDriftGroups.entries()]
        .sort((a, b) => b[1].length - a[1].length)
        .map(([key, rows]) => [key, rows.length])
    ),
    rootCauses: Object.fromEntries(
      [...byCause.entries()]
        .sort((a, b) => b[1].length - a[1].length)
        .map(([cause, rows]) => [
          cause,
          {
            count: rows.length,
            auto: rows.filter(r => r.rootCause!.confidence === 'auto').length,
            needsReview: rows.filter(
              r => r.rootCause!.confidence === 'needs-review'
            ).length,
          },
        ])
    ),
    sideChecks: {
      maskedFailures: {
        exitZeroInvocations: exitZero.length,
        masked: masked.length,
        maskedPctOfExitZero: pct(masked.length, exitZero.length),
        headlineErrorPct: pct(headlineErrors.length, total),
        revisedFailurePct: pct(headlineErrors.length + masked.length, total),
      },
      triggerRecall: {
        lumoSessions: lumoSessions.size,
        sessionsWithSkillLoad: withSkill.length,
        recallPct: pct(withSkill.length, lumoSessions.size),
        weekly: Object.fromEntries(
          [...weeklyRecall.entries()]
            .sort((a, b) => a[0].localeCompare(b[0]))
            .map(([w, v]) => [w, { ...v, recallPct: pct(v.loaded, v.total) }])
        ),
      },
      selfConditioning: clustering,
    },
    reconciliation: {
      flagHallucinationsAsUsageError: flagHallucinations.filter(
        r => r.resultClass === 'usage-error'
      ).length,
      statusWalkCalls: statusWalks.length,
      identicalRepeatCalls: identicalRepeats.length,
      unhelpfulToolErrors: unhelpfulErrors.length,
    },
  }

  writeFileSync(
    join(HERE, 'out/attribution.jsonl'),
    labeled.map(r => JSON.stringify(r)).join('\n') + '\n'
  )
  writeFileSync(
    join(HERE, 'out/attribution.json'),
    JSON.stringify(aggregates, null, 2)
  )
  writeFileSync(
    join(HERE, 'REPORT-lum413.md'),
    renderReport(aggregates, labeled)
  )

  console.log(
    `Labeled ${total} invocations across ${lumoSessions.size} sessions`
  )
  for (const c of classOrder) {
    const n = byClass.get(c)?.length ?? 0
    console.log(
      `  ${c.padEnd(16)} ${String(n).padStart(5)}  (${pct(n, total)}%)`
    )
  }
  console.log(
    `AST invalid constructions: ${astInvalid.length} (flag ${flagHallucinations.length} / enum ${enumViolations.length} / cmd ${unknownCommands.length}; ${docDrift.length} accepted at runtime → doc drift; ${truncatedSkipped} truncated raws skipped)`
  )
  console.log(
    `Masked failures: ${masked.length} → revised failure rate ${aggregates.sideChecks.maskedFailures.revisedFailurePct}% (headline ${aggregates.sideChecks.maskedFailures.headlineErrorPct}%)`
  )
  console.log(
    `Trigger recall: ${withSkill.length}/${lumoSessions.size} (${aggregates.sideChecks.triggerRecall.recallPct}%)`
  )
  console.log(
    `Self-conditioning: redundant mean pos ${clustering.meanPosRedundant?.toFixed(2) ?? 'n/a'} vs other ${clustering.meanPosOther?.toFixed(2) ?? 'n/a'}`
  )
  console.log(`Report: scripts/analysis/lum392-cli-friction/REPORT-lum413.md`)
}

function exampleRows(rows: LabeledRecord[], n: number): string[] {
  return rows
    .slice(0, n)
    .map(
      r =>
        `  - \`${r.raw.slice(0, 110)}\`` +
        (r.rootCause ? ` — ${r.rootCause.rationale}` : '') +
        (r.evidence ? ` _(evidence: ${r.evidence.slice(0, 90)})_` : '')
    )
}

function renderReport(
  agg: ReturnType<typeof JSON.parse>,
  labeled: LabeledRecord[]
): string {
  const lines: string[] = []
  const push = (s = '') => lines.push(s)
  const causeRows = Object.entries(
    agg.rootCauses as Record<
      string,
      { count: number; auto: number; needsReview: number }
    >
  )
  const dist = agg.fiveClassDistribution as Record<
    string,
    { count: number; pct: string }
  >

  push(`# LUM-413 — CLI eval failure attribution (re-run)`)
  push()
  push(
    `> Generated by \`run-attribution.ts\` over the LUM-392 extraction. Coverage: ${agg.coverage.invocations} invocations / ${agg.coverage.sessions} sessions, ${String(agg.coverage.from).slice(0, 10)} → ${String(agg.coverage.to).slice(0, 10)}. Grammar: cli v${agg.grammarCliVersion}. Read-only prod, zero schema.`
  )
  push()
  push(`## 1. Five-class result distribution`)
  push()
  push(`| Class | Count | % | Definition |`)
  push(`| --- | ---: | ---: | --- |`)
  const defs: Record<string, string> = {
    'valid-result': 'succeeded, output usable (InfoMosaic)',
    'redundant-valid':
      'succeeded but ceremonial/redundant — status walking, identical repeats (WildToolBench 5th class)',
    'usage-error': 'right tool, wrong construction (InfoMosaic)',
    'selection-error': 'nonexistent/wrong tool selected (InfoMosaic)',
    'invalid-result':
      'well-formed call, unusable result — incl. masked failures (InfoMosaic + Gorilla)',
  }
  for (const [c, v] of Object.entries(dist)) {
    push(`| ${c} | ${v.count} | ${v.pct}% | ${defs[c] ?? ''} |`)
  }
  push()
  push(`## 2. Winston root-cause table (suggestion layer — review worksheet)`)
  push()
  push(`| Root cause | Count | auto | needs-review |`)
  push(`| --- | ---: | ---: | ---: |`)
  for (const [cause, v] of causeRows) {
    push(`| ${cause} | ${v.count} | ${v.auto} | ${v.needsReview} |`)
  }
  push()
  push(
    `R4 (constrained decoding) is structurally n/a on a shell CLI surface and is never auto-suggested. Redundant-valid and interrupted calls carry no root cause (agent behavior, not a fixable tool component).`
  )
  push()
  push(`## 3. Reconciliation with LUM-392 friction findings`)
  push()
  push(
    `- **Flag hallucination ↔ usage-error / R2(R5)**: ${agg.astVerdicts.unknownFlag} unknown-flag constructions; ${agg.reconciliation.flagHallucinationsAsUsageError} errored and are labeled usage-error, the remainder were swallowed at run time (stderr suppressed) and appear in the doc-drift table instead.`
  )
  push(
    `- **状态走步 ↔ fifth class**: ${agg.reconciliation.statusWalkCalls} status-walk calls + ${agg.reconciliation.identicalRepeatCalls} identical repeats labeled redundant-valid — both taxonomies alone would have called every one of these valid-result.`
  )
  push(
    `- **错误不指路 ↔ invalid-result / R6(R5)**: ${agg.reconciliation.unhelpfulToolErrors} tool-side errors whose message offers no next step (flagged "R5 candidate" in the worksheet).`
  )
  push(
    `- **Unknown commands ↔ selection-error**: ${agg.astVerdicts.unknownCommand} unknown-command constructions.`
  )
  push()
  push(`### Flag-hallucination regression set (AST verdicts, live)`)
  push()
  exampleRows(
    labeled.filter(r => r.ast.kind === 'unknown-flag'),
    15
  ).forEach(push)
  push()
  push(
    `### Doc-behavior drift: structurally illegal per help text, accepted at run time`
  )
  push()
  push(
    `The CLI declares enums in help text only (no commander \`.choices()\`), so runtime accepts what the docs forbid. ${agg.astVerdicts.acceptedAtRuntime} invocations are in this gap (also includes stderr-suppressed runs):`
  )
  push()
  push(`| Violation · command · token | Count |`)
  push(`| --- | ---: |`)
  for (const [key, count] of Object.entries(
    agg.docDrift as Record<string, number>
  ).slice(0, 12)) {
    push(`| ${key} | ${count} |`)
  }
  push()
  push(`## 4. Side checks`)
  push()
  push(`### 4.1 Masked failures (Gorilla/Winston: does exit 0 hide failures?)`)
  push()
  const mf = agg.sideChecks.maskedFailures
  push(
    `${mf.masked} of ${mf.exitZeroInvocations} exit-0 invocations produced empty stdout (${mf.maskedPctOfExitZero}%). Headline error rate ${mf.headlineErrorPct}% → revised upper bound ${mf.revisedFailurePct}% when masked failures are counted as failures. (\`lumo hook *\` is exempt: silent-by-design.)`
  )
  push()
  push(`### 4.2 SKILL.md trigger recall`)
  push()
  const tr = agg.sideChecks.triggerRecall
  push(
    `${tr.sessionsWithSkillLoad} of ${tr.lumoSessions} lumo-using sessions loaded the lumo skill (recall ${tr.recallPct}%). Weekly trend (description-trim watch item):`
  )
  push()
  push(`| Week of | Sessions | Loaded skill | Recall |`)
  push(`| --- | ---: | ---: | ---: |`)
  for (const [w, v] of Object.entries(
    tr.weekly as Record<
      string,
      { total: number; loaded: number; recallPct: string }
    >
  )) {
    push(`| ${w} | ${v.total} | ${v.loaded} | ${v.recallPct}% |`)
  }
  push()
  push(`### 4.3 Self-conditioning (WildToolBench)`)
  push()
  const sc = agg.sideChecks.selfConditioning
  push(
    sc.redundantCalls > 0
      ? `Across ${sc.sessions} sessions (≥5 invocations), ${sc.redundantCalls} redundant calls sit at mean normalized position ${sc.meanPosRedundant.toFixed(2)} vs ${sc.meanPosOther.toFixed(2)} for everything else; ${(sc.lateHalfShareRedundant * 100).toFixed(0)}% land in the late half of their session.`
      : `No redundant calls detected in sessions with ≥5 invocations.`
  )
  push()
  push(`## 5. Method notes & limitations`)
  push()
  push(
    `- Result layer is fully automatic from HookEvent data; the root-cause layer is a suggestion worksheet (Winston labels are human labels — \`needs-review\` rows want a human/LLM pass).`
  )
  push(
    `- Sibling invocations in one Bash call share output, so runtime evidence can be misattributed; AST verdicts are per-segment and immune.`
  )
  push(
    `- Redundancy uses a ${10}-minute in-session window; a status correction within the window is indistinguishable from a walk and counts as one.`
  )
  push(
    `- AST verdicts judge construction against the CURRENT grammar — historical calls that failed against older CLI versions can legitimately differ (that is the drift-regression feature, not a bug).`
  )
  push()
  return lines.join('\n') + '\n'
}

main().catch(e => {
  console.error(e)
  process.exit(1)
})
