/**
 * LUM-915 — the privacy policy and DPA sources (docs/live-docs/legal-*.md)
 * quote the shipped retention defaults and tiers. The figures each sentence
 * names are built from the lib constants, so changing a tier or a default
 * without updating the legal sources fails here.
 */
import fs from 'fs'
import path from 'path'

import { retentionFigures } from '@/lib/legal/retention-figures'
import { AUDIT_RETENTION_DAYS } from '@/lib/audit/actions'

const ROOT = process.cwd()
const read = (rel: string) => fs.readFileSync(path.join(ROOT, rel), 'utf8')

const POLICY = 'docs/live-docs/legal-privacy-policy.md'
const DPA = 'docs/live-docs/legal-dpa-template.md'

/** "30, 90, 180 or 365": the legal sources' list style. */
function orList(days: readonly number[]): string {
  const all = days.map(String)
  return `${all.slice(0, -1).join(', ')} or ${all[all.length - 1]}`
}

/** The text of the `## heading` section, up to the next `## ` heading. */
function section(doc: string, heading: string): string {
  const start = doc.indexOf(`\n## ${heading}`)
  expect(start).toBeGreaterThanOrEqual(0)
  const end = doc.indexOf('\n## ', start + 1)
  return doc.slice(start, end === -1 ? undefined : end)
}

/** The table row whose first cell starts with `label`. */
function row(doc: string, label: string): string {
  const line = doc.split('\n').find(l => l.startsWith(`| ${label}`))
  expect(line).toBeDefined()
  return line as string
}

describe('legal retention claims LUM-915', () => {
  // LUM-1062 / LUM-1065: the scan evidence figures come from the installed
  // security plugin's retention contribution; their sentences are checked
  // with the plugin, __tests__/ee/security/lib/legal/legal-retention-claims.test.ts.
  const f = retentionFigures()

  it('privacy policy retention rows quote the retention constants', () => {
    const policy = read(POLICY)

    const session = row(policy, 'Agent hook events (session records)')
    expect(session).toMatch(/By default, for as long as the workspace exists/)
    expect(session).toContain(`${orList(f.sessionDays)} days`)
    expect(session).toContain(`deleted ${f.grace} days after it is used up`)
    expect(session).toContain(`held up to ${f.auditCap} days after completion`)
    expect(session).toContain(`${f.idle} days pass with no agent activity`)
    expect(session).toContain(`plus ${f.grace} days`)

    const crossing = row(policy, 'Boundary-crossing records')
    expect(crossing).toContain(
      `${f.crossingDefault} days after the crossing is dispositioned`
    )
    expect(crossing).toContain(`choose ${orList(f.crossingTiers)} days`)

    const deadLetter = row(policy, 'Failed pull-request comment syncs')
    expect(deadLetter).toContain(
      `deleted ${f.deadLetterDefault} days after the sync failed`
    )
    expect(deadLetter).toContain(`choose ${orList(f.deadLetterTiers)} days`)
  })

  it('legal sources describe the AI-derived content switch and delete LUM-917', () => {
    // LUM-917 (#1213): workspaces.aiDerivedContentEnabled defaults to true;
    // memory / session-summary / run-summary writes strip code before
    // redaction; the OWNER delete (workspace name re-typed) removes memories
    // and clears session and run summaries, AI-written claim snapshots and
    // faithfulness explanations, and never touches hook events.
    expect(read('prisma/schema.prisma')).toMatch(
      /aiDerivedContentEnabled Boolean @default\(true\)/
    )
    expect(read('lib/services/ai-derived-content.service.ts')).toMatch(
      /confirmName !== workspace\.name/
    )
    for (const fn of [
      'deleteMemoryBatch',
      'clearSessionSummaryBatch',
      'clearRunSummaryBatch',
      'clearClaimSnapshotBatch',
      'clearVerdictTextBatch',
    ])
      expect(read('lib/services/ai-derived-content.service.ts')).toContain(
        `aiDerivedContentRepository.${fn}(`
      )
    expect(
      read('lib/repositories/ai-derived-content.repository.ts')
    ).not.toMatch(/prisma\.hookEvent\b/)

    const derived = row(
      section(read(POLICY), 'How long we keep data'),
      'AI-derived content'
    )
    for (const claim of [
      'generated by AI from agent sessions by default',
      'code blocks and lines of code are removed and credentials are redacted before they are stored',
      'kept for as long as the workspace exists unless a workspace owner deletes them',
      'A workspace owner can turn their generation off in the data retention settings',
      'no new memories, session summaries, run summaries or AI-written task claims are generated',
      "an agent's own report on its work is still kept",
      'after re-typing the workspace name',
      'all team memory (including memories added by hand) with its search embeddings',
      'all session and run summaries, the AI-written task claims and the explanations of claim faithfulness checks',
      'Agent hook events, tasks and documents are not affected',
    ])
      expect(derived).toContain(claim)
    // The pre-LUM-917 sentence said nothing could remove them.
    expect(derived).not.toMatch(/retention settings above do not remove them/)

    const retention = row(read(DPA), 'Retention')
    for (const claim of [
      'generated by default with code removed',
      'unless Customer turns their generation off or deletes them in the same settings',
      'also clears AI-written task claims and the explanations of claim faithfulness checks',
      'does not affect agent session records',
    ])
      expect(retention).toContain(claim)
  })

  it('legal sources list session and run summaries as AI-derived content, not hook events LUM-917', () => {
    // Session and run summaries are Session columns written by the AI
    // summary services and cleared by the AI-derived delete
    // (clearSessionSummaryBatch / clearRunSummaryBatch), not hook events.
    const repo = read('lib/repositories/ai-derived-content.repository.ts')
    expect(repo).toMatch(/clearSessionSummaryBatch/)
    expect(repo).toMatch(/clearRunSummaryBatch/)

    const collected = section(read(POLICY), 'What data we collect')
    expect(row(collected, 'Agent hook events')).not.toMatch(/summar/i)
    const policyDerived = row(collected, 'AI-derived content')
    expect(policyDerived).toContain(
      'Memories extracted from agent sessions, session summaries and run summaries'
    )
    expect(policyDerived).toMatch(
      /a workspace owner can turn this off and delete what was generated/
    )

    const categories = section(read(DPA), 'Annex 1')
    expect(row(categories, 'Agent hook events')).not.toMatch(/summar/i)
    expect(row(categories, 'AI-derived content')).toContain(
      'Memories extracted from agent sessions, session summaries and run summaries'
    )
  })

  it('privacy policy describes the uninstall scrub', () => {
    // LUM-860: uninstall (and repository removal) clears scan code
    // (github-app-install.service.ts scrubWorkspaceCode); the old sentence
    // said everything collected from GitHub was kept.
    const policy = read(POLICY)
    expect(policy).not.toMatch(
      /uninstall the GitHub App but keep the workspace, data already collected from GitHub is kept/
    )
    expect(policy).toMatch(
      /uninstall the GitHub App, or remove a repository from it, but keep the workspace, we immediately clear the code stored with the affected security scans/
    )
  })

  it('DPA retention row quotes the retention constants', () => {
    const dpa = read(DPA)
    const retention = row(dpa, 'Retention')
    expect(retention).toContain(
      `${orList(f.sessionDays)} days after each event`
    )
    expect(retention).toContain(
      `discarded ${f.grace} days after they are used up`
    )
    expect(retention).toContain(
      `${f.crossingDefault} days after disposition by default (${orList(f.crossingTiers)} days selectable)`
    )
    expect(retention).toContain(
      `deleted ${f.deadLetterDefault} days after the failure by default (${orList(f.deadLetterTiers)} days selectable)`
    )
  })

  it('legal sources claim no Lumo-side encryption of session records', () => {
    // Storage relies on the providers' at-rest encryption; the only
    // application-layer encryption is for integration tokens (lib/crypto.ts).
    for (const doc of [read(POLICY), read(DPA)]) {
      for (const line of doc.split('\n')) {
        if (/AES-256-GCM/.test(line))
          expect(line).toMatch(/integration access tokens/i)
        expect(line).not.toMatch(
          /per-workspace key|separate key|crypto-?shred/i
        )
      }
    }
  })

  it('legal sources no longer describe acceptance criteria or lumo verify', () => {
    // LUM-942 (#1209/#1210/#1211) removed acceptance criteria, lumo verify and
    // verification rounds; test cases remain, and DONE is held only by open
    // boundary crossings, blocking security findings and test-case defects
    // (lib/services/done-verdict.service.ts).
    for (const doc of [read(POLICY), read(DPA)]) {
      expect(doc).not.toMatch(
        /acceptance criteri|acceptance verification|verifying acceptance|agent-verification|lumo verify|verification round|verdict/i
      )
      // The only "verify" left is identity verification for rights requests.
      for (const line of doc.split('\n'))
        if (/verif/i.test(line)) expect(line).toMatch(/verify your identity/)
    }
    expect(row(read(POLICY), 'Workspace content')).toMatch(
      /test cases and their run records/
    )
    expect(row(read(DPA), 'Workspace content')).toMatch(
      /test cases and their run records/
    )
  })

  it('legal sources disclose the workspace audit log LUM-907', () => {
    // PR1 records actor, IP, user agent and (invites) the invitee email;
    // the daily prune keeps AUDIT_RETENTION_DAYS; rows cascade with the
    // workspace; the GDPR export carries them.
    const policy = read(POLICY)
    const collected = row(policy, 'Workspace audit log | A record')
    expect(collected).toContain('IP address and user agent')
    expect(collected).toContain("the invitee's email address")
    const kept = row(policy, 'Workspace audit log | Each event')
    expect(kept).toContain(`${AUDIT_RETENTION_DAYS} days after it is recorded`)
    expect(kept).toContain('deleted with the workspace')
    expect(kept).toContain('included in the workspace export')
    expect(section(policy, 'Who we share data with')).toContain(
      'Workspace owners can also see the workspace audit log'
    )

    const dpa = read(DPA)
    expect(row(dpa, 'Retention')).toContain(
      `workspace audit log events are deleted ${AUDIT_RETENTION_DAYS} days after they are recorded`
    )
    expect(row(dpa, 'Workspace audit log')).toContain(
      'IP address and user agent'
    )
    expect(row(dpa, 'Logging and accountability')).toContain(
      `kept for ${AUDIT_RETENTION_DAYS} days`
    )
  })
})
